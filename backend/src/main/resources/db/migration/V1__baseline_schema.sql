-- Baseline schema, equal to what Hibernate generated for the entities in Entities.java.
-- Databases that already exist are marked as version 1 by Flyway (baseline-on-migrate) and skip this file.
-- Every later schema change goes into a new file: V2__what_changed.sql, V3__..., and is never edited afterwards.

CREATE TABLE customers (
    id            VARCHAR(255) PRIMARY KEY,
    name          VARCHAR(255),
    phone         VARCHAR(255),
    account_last4 VARCHAR(255)
);

CREATE TABLE invoices (
    id            VARCHAR(255) PRIMARY KEY,
    customer_id   VARCHAR(255),
    customer_name VARCHAR(255),
    amount        BIGINT NOT NULL,
    issue_date    DATE,
    due_date      DATE,
    status        VARCHAR(255),
    row_hash      VARCHAR(255),
    CONSTRAINT uk_invoices_row_hash UNIQUE (row_hash)
);

CREATE TABLE bank_transactions (
    id           VARCHAR(255) PRIMARY KEY,
    txn_date     DATE,
    amount       BIGINT NOT NULL,
    direction    VARCHAR(255),
    payer        VARCHAR(255),
    channel      VARCHAR(255),
    bank_ref     VARCHAR(255),
    reversal_ref VARCHAR(255),
    narration    VARCHAR(1000),
    row_hash     VARCHAR(255),
    CONSTRAINT uk_bank_transactions_row_hash UNIQUE (row_hash)
);

CREATE TABLE payer_aliases (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payer           VARCHAR(255),
    payer_key       VARCHAR(255),
    customer_id     VARCHAR(255),
    source          VARCHAR(255),
    confirmed_count INTEGER NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_payer_aliases_key_customer UNIQUE (payer_key, customer_id)
);

CREATE TABLE allocations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_id     VARCHAR(255),
    invoice_id VARCHAR(255),
    amount     BIGINT NOT NULL,
    method     VARCHAR(255),
    confidence FLOAT(53) NOT NULL
);

CREATE TABLE adjustments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_id     VARCHAR(255),
    invoice_id VARCHAR(255),
    amount     BIGINT NOT NULL,
    type       VARCHAR(255)
);

CREATE TABLE unapplied_credits (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_id      VARCHAR(255),
    customer_id VARCHAR(255),
    amount      BIGINT NOT NULL
);

CREATE TABLE txn_outcomes (
    txn_id          VARCHAR(255) PRIMARY KEY,
    kind            VARCHAR(255),
    channel         VARCHAR(255),
    decision        VARCHAR(255),
    method          VARCHAR(255),
    confidence      FLOAT(53) NOT NULL,
    reason          VARCHAR(1000),
    linked_txn_id   VARCHAR(255),
    candidates_json TEXT
);

CREATE TABLE manual_decisions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_id     VARCHAR(255),
    invoice_id VARCHAR(255),
    amount     BIGINT NOT NULL,
    decided_by VARCHAR(255),
    decided_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE credit_applications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_id     VARCHAR(255),
    invoice_id VARCHAR(255),
    amount     BIGINT NOT NULL,
    applied_by VARCHAR(255),
    applied_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE feedback_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_id         VARCHAR(255),
    label          INTEGER NOT NULL,
    features_json  TEXT,
    system_score   FLOAT(53) NOT NULL,
    human_decision VARCHAR(255),
    decided_by     VARCHAR(255),
    decided_at     TIMESTAMP(6) WITH TIME ZONE,
    revoked        BOOLEAN NOT NULL
);

CREATE TABLE app_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(255),
    password_hash VARCHAR(255),
    role          VARCHAR(255),
    CONSTRAINT uk_app_users_username UNIQUE (username)
);

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(255),
    entity_id   VARCHAR(255),
    action      VARCHAR(255),
    detail      TEXT,
    actor       VARCHAR(255),
    created_at  TIMESTAMP(6) WITH TIME ZONE
);
